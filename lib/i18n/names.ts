/**
 * Localizes any persona, taxpayer name, or citizen pattern into the target language.
 * Guarantees that if a user changes the portal language to Hindi, Bengali, Kannada,
 * Tamil, Urdu, Gujarati, Bodo, etc., taxpayer names cleanly change script!
 */
export function localizeName(name: string | undefined | null, lang: Lang): string {
  if (!name) return "";
  if (lang === "en") return name;
  const trimmed = name.trim();

  // 1. Direct exact match
  if (EXACT_NAMES[trimmed]?.[lang]) {
    return EXACT_NAMES[trimmed]![lang]!;
  }

  // Case-insensitive exact match
  const matchKey = Object.keys(EXACT_NAMES).find(
    (k) => k.toLowerCase() === trimmed.toLowerCase()
  );
  if (matchKey && EXACT_NAMES[matchKey]?.[lang]) {
    return EXACT_NAMES[matchKey]![lang]!;
  }

  // 2. Pattern: "Citizen 1234" -> "नागरिक 1234" etc.
  const citizenMatch = trimmed.match(/^citizen\s+(\d{3,5})$/i);
  if (citizenMatch) {
    const prefix = CITIZEN_PREFIXES[lang] ?? "नागरिक";
    return `${prefix} ${citizenMatch[1]}`;
  }

  // 3. CA title pattern: "CA Rajesh Sharma" or "CA Rajesh Sharma, FCA"
  if (/^CA\s+/i.test(trimmed)) {
    const withoutCa = trimmed.replace(/^CA\s+/i, "");
    const localizedInner = localizeName(withoutCa, lang);
    const caPrefix = (lang === "hi" || lang === "mr" || lang === "ne") ? "सीए " : ((lang === "bn" || lang === "as") ? "সিএ " : ((lang === "ur" || lang === "ks" || lang === "sd") ? "سی اے " : "CA "));
    return `${caPrefix}${localizedInner}`;
  }

  // 4. Word-by-word tokenized transliteration
  const tokens = trimmed.split(/\s+/);
  if (tokens.length > 1) {
    const translatedTokens = tokens.map((token) => {
      // Check word map
      const direct = WORD_MAP[token]?.[lang];
      if (direct) return direct;
      const ciKey = Object.keys(WORD_MAP).find((k) => k.toLowerCase() === token.toLowerCase());
      if (ciKey && WORD_MAP[ciKey]?.[lang]) return WORD_MAP[ciKey]![lang]!;
      return token;
    });

    // If at least one token got localized, return the joined tokens
    const anyLocalized = translatedTokens.some((t, i) => t !== tokens[i]);
    if (anyLocalized) {
      return translatedTokens.join(" ");
    }
  }

  // Single word token
  const singleMatch = WORD_MAP[trimmed]?.[lang];
  if (singleMatch) return singleMatch;

  return name;
}
